async function fetchText(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url} → ${r.status}`);
  return r.text();
}

function parseStops(svg) {
  const stops = [];
  const re =
    /<stop\s+offset="([0-9.]+)%"\s+stop-color="(#[0-9a-fA-F]{3,8})"\s*\/>/g;
  for (const m of svg.matchAll(re)) {
    stops.push({ offset: parseFloat(m[1]), color: m[2] });
  }
  return stops;
}

function parseSwatch(svg) {
  const colors = [];
  const re = /<rect[^>]*fill="(#[0-9a-fA-F]{3,8})"[^>]*\/>/g;
  for (const m of svg.matchAll(re)) {
    colors.push(m[1]);
  }
  return colors;
}

async function main() {
  const discreteResults = await Promise.all(
    DISCRETE.map(async (name) => {
      const svg = await fetchText(`${RAW_BASE}swatch_${name}.svg`);
      return { name, colors: parseSwatch(svg) };
    }),
  );

  const continuousResults = await Promise.all(
    CONTINUOUS.map(async ([name, category]) => {
      const svg = await fetchText(`${RAW_BASE}gradient_${name}.svg`);
      return { name, category, stops: parseStops(svg) };
    }),
  );

  const ts = `// Auto-generated by scripts/extract-palettes.mjs.
// Source: https://github.com/posit-dev/ggsql/tree/main/doc/syntax/scale/aesthetic/examples
// Do not edit by hand — re-run the script and commit the result.

export const DEFAULT_DISCRETE = "ggsql10";
export const DEFAULT_CONTINUOUS = "sequential";

export interface DiscretePalette {
  name: string;
  colors: string[];
}

export type ContinuousCategory = "sequential" | "diverging" | "multi" | "cyclic";

export interface ContinuousPalette {
  name: string;
  category: ContinuousCategory;
  stops: Array<{ offset: number; color: string }>;
}

export const DISCRETE_PALETTES: DiscretePalette[] = ${JSON.stringify(
    discreteResults,
    null,
    2,
  )};

export const CONTINUOUS_PALETTES: ContinuousPalette[] = ${JSON.stringify(
    continuousResults,
    null,
    2,
  )};

export function gradientCss(stops: Array<{ offset: number; color: string }>): string {
  return (
    "linear-gradient(to right, " +
    stops.map((s) => \`\${s.color} \${s.offset}%\`).join(", ") +
    ")"
  );
}
`;

  writeFileSync(OUT_PATH, ts);
  console.log(
    `wrote ${OUT_PATH}: ${discreteResults.length} discrete, ${continuousResults.length} continuous`,
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
